// N-25 예행(가짜 DB: PGlite). 운영 확인이 아님. 사용: node 이파일 [apply.sql 경로 덮어쓰기]
import { PGlite } from '@electric-sql/pglite';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const D = path.dirname(fileURLToPath(import.meta.url));
const applyPath = process.argv[2] || path.join(D, '2026-10-28_client_error_logs_real_apply.sql');
const rollbackPath = path.join(D, '2026-10-28_client_error_logs_real_rollback.sql');
const db = new PGlite(); const out = [];
const ok = (l, c, d) => out.push((c ? '✅ ' : '❌ ') + l + (d ? ' — ' + d : ''));
await db.exec(`
create role anon; create role authenticated; create role service_role;
create table public.client_error_logs (id bigint generated by default as identity primary key, created_at timestamptz default now(), app text, message text, stack text, url text, user_role text, user_name text, build text, extra jsonb);
alter table public.client_error_logs enable row level security;
-- 원본 정책 모사(가정): 로그인 사용자만 읽기, 누구나 쓰기
create policy r on public.client_error_logs for select to authenticated using (true);
create policy w on public.client_error_logs for insert to anon, authenticated with check (true);
grant usage on schema public to anon, authenticated, service_role;
grant select, insert on public.client_error_logs to authenticated;
grant insert on public.client_error_logs to anon;
grant all on public.client_error_logs to service_role;
`);
const ins = (m, e) => db.query('insert into public.client_error_logs(app,message,extra) values ($1,$2,$3)', ['estimate', m, e == null ? null : JSON.stringify(e)]);
// 진행 기록(정상) 6종
for (const m of ['시작', '세션확인-정상', '검증통과', '필수항목검증완료', '확인창-진행']) await ins('저장단계: ' + m, { stage: m });
await ins('저장단계: 고객저장-응답', { stage: '고객저장-응답', detail: { status: 201 } });
await ins('저장단계: 견적서저장-응답', { stage: '견적서저장-응답', detail: { status: 200 } });
// 진짜 오류 + 진행 기록 속 문제 신호
await ins('Uncaught TypeError: x is not a function', null);
await ins('저장 실패(동시저장충돌) - 내용 백업됨', { a: 1 });
await ins(null, null);
await ins('저장단계: 견적서저장-타임아웃', null);
await ins('저장단계: 고객저장-예외', { detail: { message: 'boom' } });
await ins('저장단계: 견적서저장-응답', { stage: '견적서저장-응답', detail: { status: 409 } });
await ins('저장단계: 고객저장-응답', { stage: '고객저장-응답' }); // 상태 못 읽음 → 문제로 남김
const cnt = async (t) => Number((await db.query(`select count(*)::int c from ${t}`)).rows[0].c);
const msgs = async () => (await db.query('select message from public.client_error_logs_real')).rows.map(r => r.message);
const base0 = await cnt('public.client_error_logs');
ok('시험 데이터 준비: 원본 14건', base0 === 14, String(base0));
await db.exec(fs.readFileSync(applyPath, 'utf8'));
const real = await msgs();
ok('진행 기록 7건(정상 5 + 응답 2xx 2)은 보기에서 빠짐', !real.some(m => ['저장단계: 시작','저장단계: 세션확인-정상','저장단계: 검증통과','저장단계: 필수항목검증완료','저장단계: 확인창-진행'].includes(m)) && real.filter(m => m && m.endsWith('-응답')).length === 2, '보기 ' + real.length + '건');
ok('진짜 오류(JS 오류·동시저장충돌·메시지 없는 행)는 남음', real.includes('Uncaught TypeError: x is not a function') && real.includes('저장 실패(동시저장충돌) - 내용 백업됨') && real.includes(null));
ok('진행 기록 속 문제 신호(타임아웃·예외·409·상태불명)는 남음', real.includes('저장단계: 견적서저장-타임아웃') && real.includes('저장단계: 고객저장-예외') && real.length === 7, '보기 ' + real.length + '건');
ok('원본 건수 불변(14건)', (await cnt('public.client_error_logs')) === 14);
const opt = (await db.query("select reloptions::text r from pg_class where relname='client_error_logs_real'")).rows[0].r;
ok('security_invoker=true 설정됨', /security_invoker=true/.test(opt), opt);
await db.exec('set role anon');
let anonErr = null; try { await db.query('select * from public.client_error_logs_real'); } catch (e) { anonErr = e.message; }
await db.exec('reset role');
ok('anon은 보기를 못 읽음', /permission denied/.test(String(anonErr)), String(anonErr));
await db.exec('set role authenticated');
const authN = await cnt('public.client_error_logs_real');
await db.exec('reset role');
ok('authenticated는 읽음(원본 정책 통과)', authN === 7, String(authN));
// RLS 상속: authenticated 읽기 정책을 없애면 보기도 0건(원본 RLS가 그대로 적용된다는 증거)
await db.exec('drop policy r on public.client_error_logs');
await db.exec('set role authenticated');
const authN2 = await cnt('public.client_error_logs_real');
await db.exec('reset role');
ok('원본 읽기 정책을 없애면 보기도 0건(RLS 상속)', authN2 === 0, String(authN2));
await db.exec('create policy r on public.client_error_logs for select to authenticated using (true)');
await db.exec(fs.readFileSync(rollbackPath, 'utf8'));
const ex = (await db.query("select count(*)::int c from pg_class where relname='client_error_logs_real'")).rows[0].c;
ok('되돌리면 보기가 없음', ex === 0);
ok('되돌린 뒤에도 원본 14건 그대로', (await cnt('public.client_error_logs')) === 14);
console.log(out.join('\n')); const bad = out.some(l => l.startsWith('❌'));
console.log(bad ? '\n❌ 실패 있음' : '\n✅ 모두 통과 (가짜 DB 예행 — 운영 확인 아님)'); process.exit(bad ? 1 : 0);
