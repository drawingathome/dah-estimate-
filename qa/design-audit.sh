#!/bin/bash
# design-audit.sh — DAH 프로젝트 "확정값 드리프트" 통합 감사 도구
# 목적: 색상/단계배열/수수료/폰트/radius처럼 "여러 곳에 따로 정의될 수 있는 확정값"이
# 코드베이스에 몇 군데 있고, 서로 일치하는지 한 번에 스캔한다.
# 사용법: bash design-audit.sh (레포 루트에서 실행)

echo "════════════════════════════════════════"
echo "1. 스테이지 배열(9단계) 중복 정의 지점"
echo "════════════════════════════════════════"
grep -n "'방문예약','상담','가견적','선금결제','실측준비중','확정견적','잔금결제','시공준비중','시공완료'" *.js
echo ""

echo "════════════════════════════════════════"
echo "2. 스테이지→컬러 매핑이 있는 모든 지점 (3색 원칙: 8A8378/terra/2E7D6B)"
echo "════════════════════════════════════════"
grep -n "8A8378" *.js *.css | grep -iv "border\|background:#F0EFEC\|comment" | head -30
echo ""

echo "════════════════════════════════════════"
echo "3. 지역출장비(서울/경기) 하드코딩 지점"
echo "════════════════════════════════════════"
grep -n "40000\|50000\|60000\|80000" *.js | grep -i "실측\|시공비\|region\|서울\|경기"
echo ""

echo "════════════════════════════════════════"
echo "4. 견적 계산 핵심 상수 (배율/레일단가/설치비) 하드코딩 지점"
echo "════════════════════════════════════════"
grep -n "1600\|25000\|10000" est-product-calc.js | grep -i "레일\|블라인드\|설치"
echo ""

echo "════════════════════════════════════════"
echo "5. border-radius 규정외 값 (허용: 4/8/12/14px, 50%)"
echo "════════════════════════════════════════"
grep -oE "border-radius:\s*[0-9]+px" dash-styles.css est-styles.css 2>/dev/null | sort | uniq -c | sort -rn | grep -vE ":\s*(4|8|12|14)px"
echo ""

echo "════════════════════════════════════════"
echo "6. 폰트 사이즈 규정외 값 (허용: 10/11/12/13/15/17/22/26/28/36px)"
echo "════════════════════════════════════════"
grep -oE "font-size:\s*[0-9]+px" dash-styles.css est-styles.css 2>/dev/null | sort | uniq -c | sort -rn | grep -vE ":\s*(10|11|12|13|15|17|22|26|28|36)px"
echo ""

echo "════════════════════════════════════════"
echo "7. !important 총 개수 (기준: 지침문서상 732개, 증감 추적용)"
echo "════════════════════════════════════════"
grep -c "!important" dash-styles.css est-styles.css 2>/dev/null

echo ""
echo "════════════════════════════════════════"
echo "8. 콜백에 함수 그대로 전달하는 위험 패턴 (7-2 규칙)"
echo "════════════════════════════════════════"
grep -nE "Async\([a-zA-Z_]+\)" *.js | grep -v "function(" 
